//! Parser for `/quoro/config`.
//!
//! The format is specified in `../../config-format.md`: one `key=value` per
//! line, split on the *first* `=`, `#` comments and blank lines ignored, any
//! unknown key is a fatal error. This module is pure so it can be tested on the
//! host: everything that touches the VM lives in `main.rs`.

/// Everything `/quoro/config` can say, already validated.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Config {
    /// `arg=` lines in order; `args[0]` is the program. Never empty.
    pub args: Vec<String>,
    /// `env=` lines in order, each `NAME=VALUE`, passed to execve verbatim.
    pub env: Vec<String>,
    /// Numeric user id the app runs as.
    pub uid: u32,
    /// Numeric primary group id the app runs as.
    pub gid: u32,
    /// Absolute working directory; `/` when the image sets none.
    pub workdir: String,
    /// Optional hostname to set before starting the app.
    pub hostname: Option<String>,
}

/// Parse the config text. Every error carries enough context to point at the
/// offending line; callers turn it into a `FATAL` line.
pub fn parse_config(input: &str) -> Result<Config, String> {
    let mut args: Vec<String> = Vec::new();
    let mut env: Vec<String> = Vec::new();
    let mut uid: Option<u32> = None;
    let mut gid: Option<u32> = None;
    let mut workdir: Option<String> = None;
    let mut hostname: Option<String> = None;

    for (idx, line) in input.lines().enumerate() {
        let line_no = idx + 1;

        if line.is_empty() || line.starts_with('#') {
            continue;
        }

        let (key, value) = match line.split_once('=') {
            Some(kv) => kv,
            None => {
                return Err(format!(
                    "line {line_no}: expected key=value, got {line:?}"
                ))
            }
        };

        match key {
            "arg" => args.push(value.to_string()),
            "env" => env.push(value.to_string()),
            "uid" => uid = Some(parse_id(value, "uid", line_no)?),
            "gid" => gid = Some(parse_id(value, "gid", line_no)?),
            "workdir" => workdir = Some(value.to_string()),
            "hostname" => hostname = Some(value.to_string()),
            other => {
                return Err(format!(
                    "line {line_no}: unknown key {other:?} (allowed: arg, env, uid, gid, workdir, hostname)"
                ))
            }
        }
    }

    if args.is_empty() {
        return Err("missing arg: at least one `arg=` line is required".to_string());
    }
    let uid = uid.ok_or_else(|| "missing uid: a `uid=` line is required".to_string())?;
    let gid = gid.ok_or_else(|| "missing gid: a `gid=` line is required".to_string())?;

    Ok(Config {
        args,
        env,
        uid,
        gid,
        workdir: workdir.unwrap_or_else(|| "/".to_string()),
        hostname,
    })
}

/// Parse a numeric id. `u32` because Linux ids are 32-bit and a negative or
/// oversized value is a config bug, not something to guess around.
fn parse_id(value: &str, key: &str, line_no: usize) -> Result<u32, String> {
    value
        .parse::<u32>()
        .map_err(|_| format!("line {line_no}: {key} is not a number: {value:?}"))
}

#[cfg(test)]
mod tests {
    use super::*;

    const EXAMPLE: &str = "\
# generated by oci2rootfs from docker.io/library/alpine@sha256:...
arg=/bin/sh
arg=-c
arg=echo hello from alpine; cat /etc/alpine-release
env=PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin
uid=0
gid=0
workdir=/
hostname=spike
";

    #[test]
    fn parses_the_documented_example() {
        let cfg = parse_config(EXAMPLE).expect("example must parse");
        assert_eq!(
            cfg.args,
            vec![
                "/bin/sh".to_string(),
                "-c".to_string(),
                "echo hello from alpine; cat /etc/alpine-release".to_string(),
            ]
        );
        assert_eq!(
            cfg.env,
            vec!["PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin".to_string()]
        );
        assert_eq!(cfg.uid, 0);
        assert_eq!(cfg.gid, 0);
        assert_eq!(cfg.workdir, "/");
        assert_eq!(cfg.hostname.as_deref(), Some("spike"));
    }

    #[test]
    fn defaults_workdir_to_root_and_hostname_to_none() {
        let cfg = parse_config("arg=/bin/true\nuid=1000\ngid=1000\n").expect("minimal config");
        assert_eq!(cfg.workdir, "/");
        assert_eq!(cfg.hostname, None);
        assert!(cfg.env.is_empty());
    }

    #[test]
    fn keeps_equals_signs_inside_values() {
        let cfg = parse_config(
            "arg=/bin/sh\narg=-c\narg=x=1; echo a=b\nenv=FOO=bar=baz\nuid=1\ngid=1\n",
        )
        .expect("values may contain '='");
        assert_eq!(cfg.args[2], "x=1; echo a=b");
        assert_eq!(cfg.env, vec!["FOO=bar=baz".to_string()]);
    }

    #[test]
    fn ignores_comments_and_blank_lines() {
        let cfg = parse_config(
            "# leading comment\n\narg=/bin/true\n# inner comment\nuid=0\ngid=0\n\n",
        )
        .expect("comments ignored");
        assert_eq!(cfg.args, vec!["/bin/true".to_string()]);
    }

    #[test]
    fn rejects_unknown_keys() {
        let err = parse_config("arg=/bin/true\nuid=0\ngid=0\ncapabilities=all\n")
            .expect_err("unknown key must fail");
        assert!(err.contains("unknown key"), "unexpected error: {err}");
        assert!(err.contains("capabilities"), "error names the key: {err}");
    }

    #[test]
    fn rejects_missing_arg() {
        let err = parse_config("uid=0\ngid=0\n").expect_err("missing arg must fail");
        assert!(err.contains("missing arg"), "unexpected error: {err}");
    }

    #[test]
    fn rejects_missing_uid_and_gid() {
        let err = parse_config("arg=/bin/true\ngid=0\n").expect_err("missing uid must fail");
        assert!(err.contains("missing uid"), "unexpected error: {err}");

        let err = parse_config("arg=/bin/true\nuid=0\n").expect_err("missing gid must fail");
        assert!(err.contains("missing gid"), "unexpected error: {err}");
    }

    #[test]
    fn rejects_non_numeric_ids() {
        let err = parse_config("arg=/bin/true\nuid=root\ngid=0\n").expect_err("bad uid must fail");
        assert!(err.contains("uid is not a number"), "unexpected error: {err}");
    }

    #[test]
    fn rejects_lines_without_equals() {
        let err = parse_config("arg=/bin/true\nuid=0\ngid=0\ngarbage\n")
            .expect_err("line without '=' must fail");
        assert!(err.contains("line 4"), "error names the line: {err}");
    }
}
