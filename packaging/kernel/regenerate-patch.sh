#!/bin/sh
# Rebuild packaging/kernel/patches/cloud-hypervisor.patch from Cloud
# Hypervisor's guest kernel branch, so a reviewer can check that the vendored
# patch is exactly their changes and nothing else.
#
#   packaging/kernel/regenerate-patch.sh            # write the patch
#   packaging/kernel/regenerate-patch.sh --check    # compare, change nothing
#
# It fetches CH_BASE..CH_HEAD from CH_REPOSITORY (kernel.txt) without blobs
# outside the touched files, takes the diff of the paths listed below, and
# refuses to run if the series touches any path it does not classify. Needs git
# and network access to GitHub. The build itself never fetches the patch.
set -eu

# Paths of the series that go into the patch: every code change, and the
# x86_64 defconfig. Code for other architectures is included as-is (it is not
# compiled for x86_64) so the series stays whole.
INCLUDED='arch/arm64/kernel/head.S
arch/x86/configs/ch_defconfig
drivers/tty/serial/amba-pl011.c
drivers/watchdog/Kconfig
drivers/watchdog/Makefile
drivers/watchdog/virtio_wdt.c
include/linux/amba/serial.h
init/main.c'

# Paths left out, and why:
#   .github/workflows/release.yaml   their CI
#   README.md                        their documentation
#   arch/arm64/configs/ch_defconfig  other architectures' configs
#   arch/riscv/configs/ch_defconfig
#   drivers/virt/vmgenid.c           "virt: vmgenid: remap memory as decrypted"
#                                    is a stable backport (upstream commit
#                                    1b48c13075829ee4961feeabd816dac1c9111959)
#                                    and is already in 7.2.15
EXCLUDED='.github/workflows/release.yaml
README.md
arch/arm64/configs/ch_defconfig
arch/riscv/configs/ch_defconfig
drivers/virt/vmgenid.c'

die() {
	printf 'regenerate-patch: %s\n' "$*" >&2
	exit 1
}

check=0
case "${1:-}" in
'') ;;
--check) check=1 ;;
*) die "usage: regenerate-patch.sh [--check]" ;;
esac

here=$(cd "$(dirname "$0")" && pwd -P) || die "cannot resolve the script directory"
recipe="$here/kernel.txt"

value() {
	awk -F= -v k="$1" '$1 == k { sub(/^[^=]*=/, ""); print; found = 1 } END { exit !found }' "$recipe" ||
		die "kernel.txt has no $1"
}

repo=$(value CH_REPOSITORY)
base=$(value CH_BASE)
head=$(value CH_HEAD)
patch="$here/$(value PATCH)"

work=$(mktemp -d "${TMPDIR:-/tmp}/regenerate-patch.XXXXXX") || die "cannot create a work directory"
trap 'rm -rf "$work"' EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

git init -q "$work/repo"
git -C "$work/repo" remote add origin "$repo"
# The series is a few dozen commits on top of the base; 64 is enough depth
# and the blob filter keeps the fetch to a few MB.
git -C "$work/repo" fetch -q --depth=64 --filter=blob:none origin "$head" ||
	die "cannot fetch $head from $repo"
git -C "$work/repo" merge-base --is-ancestor "$base" "$head" ||
	die "$base is not an ancestor of $head (deepen the fetch?)"

touched=$(git -C "$work/repo" diff --name-only --no-renames "$base" "$head" | LC_ALL=C sort)
known=$(printf '%s\n%s\n' "$INCLUDED" "$EXCLUDED" | LC_ALL=C sort)
if [ "$touched" != "$known" ]; then
	printf 'touched by the series:\n%s\n\nclassified here:\n%s\n' "$touched" "$known" >&2
	die "the series touches paths this script does not classify; review them and update INCLUDED or EXCLUDED"
fi

# shellcheck disable=SC2086 # INCLUDED is a newline-separated path list
{
	printf '%s\n' \
		"Cloud Hypervisor guest kernel changes for Quoro's guest kernel (ADR 0152)." \
		"" \
		"SPDX-License-Identifier: GPL-2.0-only" \
		"" \
		"Source: $repo" \
		"Diff:   $base (Linux 7.2.8) .. $head" \
		"Paths:  every code change of the series and arch/x86/configs/ch_defconfig;" \
		"        other architectures' configs, README, CI and the vmgenid stable" \
		"        backport are left out (packaging/kernel/regenerate-patch.sh)." \
		"" \
		"Generated by packaging/kernel/regenerate-patch.sh; do not edit by hand." \
		""
	IFS='
'
	git -C "$work/repo" -c core.quotepath=false diff --full-index --no-renames \
		--no-color --no-ext-diff "$base" "$head" -- $INCLUDED
} >"$work/cloud-hypervisor.patch" || die "cannot write the patch"

if [ "$check" = 1 ]; then
	if cmp -s "$work/cloud-hypervisor.patch" "$patch"; then
		printf 'regenerate-patch: %s matches %s..%s\n' "$patch" "$base" "$head"
		exit 0
	fi
	diff -u "$patch" "$work/cloud-hypervisor.patch" | head -40 >&2 || true
	die "$patch differs from the regenerated patch"
fi

mkdir -p "$(dirname "$patch")"
cp "$work/cloud-hypervisor.patch" "$patch"
printf 'regenerate-patch: wrote %s from %s..%s\n' "$patch" "$base" "$head"
